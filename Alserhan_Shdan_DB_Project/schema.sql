CREATE TABLE ARTIST(
ARTIST_ID int NOT NULL,
ARTIST_NAME varchar(30) NOT NULL,
GENRE varchar(30) NOT NULL,
PRIMARY KEY(ARTIST_ID)
);


CREATE TABLE CONCERT(
CONCERT_ID int NOT NULL,
ARTIST_ID int NOT NULL,
VENUE_NAME varchar(50) NOT NULL,
CITY varchar(30) NOT NULL,
CONCERT_DAY DATE NOT NULL,
PRIMARY KEY(CONCERT_ID),
FOREIGN KEY (ARTIST_ID) REFERENCES ARTIST(ARTIST_ID) ON DELETE CASCADE,
UNIQUE (ARTIST_ID, VENUE_NAME, CITY, CONCERT_DAY)
);


CREATE TABLE CUSTOMER(
CUSTOMER_ID int NOT NULL,
CUSTOMER_NAME VARCHAR(50) NOT NULL,
PRIMARY KEY(CUSTOMER_ID)
);


CREATE TABLE TICKET(
TICKET_ID INT NOT NULL,
CONCERT_ID INT NOT NULL,
CUSTOMER_ID INT NOT NULL,
SEAT_NUMBER VARCHAR(50) NOT NULL,
PRICE DECIMAL(8,2) NOT NULL,
PRIMARY KEY(TICKET_ID),
FOREIGN KEY (CONCERT_ID) REFERENCES CONCERT(CONCERT_ID) ON DELETE CASCADE,
FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID) ON DELETE CASCADE,
CHECK (PRICE>0),
UNIQUE (CONCERT_ID, SEAT_NUMBER)
);


CREATE TABLE REWARD (
    REWARD_ID INT NOT NULL AUTO_INCREMENT,
    CUSTOMER_ID INT NOT NULL,
    AMOUNT_AT_ISSUE DECIMAL(8,2) NOT NULL,
    ISSUED_DATE DATE NOT NULL,
    REDEEMED_TICKET_ID INT DEFAULT NULL,
    REDEEMED_DATE DATE DEFAULT NULL,
    PRIMARY KEY (REWARD_ID),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID) ON DELETE CASCADE,
    FOREIGN KEY (REDEEMED_TICKET_ID) REFERENCES TICKET(TICKET_ID) ON DELETE SET NULL,
    UNIQUE (REDEEMED_TICKET_ID)
);


